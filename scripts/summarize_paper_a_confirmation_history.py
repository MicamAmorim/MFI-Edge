#!/usr/bin/env python3
"""Summarize pre-data historical source references WITHOUT accessing GT or F1.

Reads only the existing historical_source_audit.json generated by the
pre-data history scanner. All classifications are review hints, not proof
that a historical campaign executed on any image.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "results/local_dev/paper_a_confirmation_inventory/predata_audit"
STRONG_TRAIN = re.compile(
    r"(?i)(?:biped.{0,90}\btrain\b|\btrain\b.{0,90}biped|edges[/\\]imgs[/\\]train)"
)
TEST = re.compile(
    r"(?i)(?:biped.{0,90}\btest\b|\btest\b.{0,90}biped|edges[/\\]imgs[/\\]test)"
)
RUN_LIKELY = re.compile(
    r"(?i)(?:read|load|glob|iterdir|image_dir|data_root|train_dir|path|dataset|split|default)"
)


def group(entry: dict) -> str:
    snippet = str(entry.get("source_excerpt", ""))
    if entry.get("mentions_candidate_ids"):
        return "explicit_candidate_id_reference"
    if STRONG_TRAIN.search(snippet):
        return "train_path_or_split_reference_REVIEW"
    if TEST.search(snippet):
        return "test_path_or_split_reference"
    if "BIPED" in snippet.upper():
        return "generic_biped_reference"
    return "other_pattern_reference"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input", type=Path, default=BASE / "historical_source_audit.json")
    ap.add_argument("--out", type=Path, default=BASE / "historical_source_triage.csv")
    ap.add_argument("--max-show", type=int, default=25)
    args = ap.parse_args()
    data = json.loads(args.input.read_text(encoding="utf-8"))
    if data.get("status") != "HISTORY_SOURCE_AUDIT_ONLY_NOT_CERTIFIED":
        ap.error("Unexpected pre-data historical audit status")
    entries = data.get("source_references", [])
    if not isinstance(entries, list):
        ap.error("Missing source reference list")
    if data.get("unique_source_references", 0) > len(entries):
        ap.error("Audit source references truncated: rerun history with --max-findings 1000")
    counts = Counter()
    per_path = defaultdict(Counter)
    rows = []
    for entry in entries:
        label = group(entry)
        counts[label] += 1
        per_path[str(entry.get("path", ""))][label] += 1
        excerpt = str(entry.get("source_excerpt", ""))
        rows.append({
            "triage_class": label,
            "path": entry.get("path", ""),
            "line_number": entry.get("line_number", ""),
            "ref_first_seen": entry.get("ref_first_seen", ""),
            "candidate_id_mentions": "|".join(entry.get("mentions_candidate_ids", [])),
            "source_excerpt": excerpt,
            "could_reference_data_access": bool(RUN_LIKELY.search(excerpt)),
            "review_status": "PENDING",
        })
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]) if rows else [
            "triage_class", "path", "line_number", "ref_first_seen",
            "candidate_id_mentions", "source_excerpt", "could_reference_data_access",
            "review_status"
        ])
        writer.writeheader()
        writer.writerows(rows)
    prioritized = sorted(
        (x for x in rows if x["triage_class"] in {
            "explicit_candidate_id_reference", "train_path_or_split_reference_REVIEW"
        }),
        key=lambda x: (
            0 if x["triage_class"] == "explicit_candidate_id_reference" else 1,
            0 if x["could_reference_data_access"] else 1,
            str(x["path"]),
            str(x["line_number"]),
        )
    )
    result = {
        "status": "CODE_REFERENCE_TRIAGE_ONLY_NOT_CERTIFIED",
        "candidate_count": data["candidate_count"],
        "unique_source_references": data["unique_source_references"],
        "class_counts": dict(counts),
        "metadata_candidate_matches": len(data.get("metadata_candidate_matches", [])),
        "top_paths": [
            {"path": p, "references": sum(v.values()),
             "train_references": v["train_path_or_split_reference_REVIEW"]}
            for p, v in sorted(per_path.items(),
                key=lambda item: (-sum(item[1].values()), item[0]))[:20]
        ],
        "priority_references": prioritized[:max(0, args.max_show)],
        "triage_csv": str(args.out),
        "independence_certified": False,
        "warning": (
            "Static grep/code mentions do not prove any historical run read "
            "BIPED train. No F1/GT read; manually inspect the cited run paths, "
            "local output manifests and chronological decisions before freeze."
        )
    }
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
