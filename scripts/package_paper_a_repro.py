MAX_FILE_BYTES = 750_000
MAX_TOTAL_BYTES = 7_000_000


def checksum(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def git_hash() -> str:
    r = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT,
                       capture_output=True, text=True, check=False)
    return r.stdout.strip() if r.returncode == 0 else "unknown"


def latest_safe_audit(directory: Path) -> tuple[str, bytes] | None:
    candidates = sorted(directory.glob("prefreeze_*.json"), reverse=True) if directory.is_dir() else []
    for candidate in candidates[:10]:
        if candidate.is_symlink() or not candidate.is_file() or candidate.stat().st_size > MAX_FILE_BYTES:
            continue
        content = candidate.read_bytes()
        try:
            record = json.loads(content)
        except (UnicodeError, json.JSONDecodeError):
            continue
        if (record.get("GT_H5_F1_or_confirmatory_data_opened") is False and
                record.get("new_training_or_descriptor_reprocessing") is False and
                record.get("cohort_frozen") is False):
            return ("audit/" + candidate.name, content)
    return None


def build_bundle(outdir: Path, audit_dir: Path) -> dict:
    outdir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S_%fZ")
    outzip = outdir / ("PaperA_repro_preconfirmatory_" + stamp + ".zip")
    entries: dict[str, bytes] = {}
    total = 0
    for relative in FILES:
        path = ROOT / relative
        if not path.is_file():
            # Both NIGHTLY_PROGRESS and the exact, workstation-reviewed P1
            # JSON are optional until the researcher explicitly exports them.
            if relative in (
                    "docs/paper_a_confirmation/NIGHTLY_PROGRESS.md",
                    "docs/paper_a_confirmation/P1_DEVELOPMENT_RECIPE_UNATTESTED.json"):
                continue
            raise FileNotFoundError("Explicit package file missing: " + relative)
        if path.is_symlink() or not path.resolve().is_relative_to(ROOT.resolve()):
            raise ValueError("Unsafe path in package: " + relative)
        data = path.read_bytes()
        if len(data) > MAX_FILE_BYTES:
            raise ValueError("File above evidence-package size limit: " + relative)
        total += len(data)
        entries[relative] = data
    extra = latest_safe_audit(audit_dir)
    if extra:
        entries[extra[0]] = extra[1]
        total += len(extra[1])
    if total > MAX_TOTAL_BYTES:
        raise ValueError("Repro evidence package too large; investigate")
    manifest = {
        "schema_version": 1,
        "status": "PRECONFIRMATORY_REPRODUCIBILITY_SNAPSHOT_NOT_CONFIRMATORY_RESULTS",
        "source_git_head": git_hash(),
        "created_utc": datetime.now(timezone.utc).isoformat(),
        "includes_confirmatory_GT_H5_F1": False,
        "includes_raw_images_or_npy_maps": False,
        "external_numerical_tierA_reference": "results/paper_a_evidence/stage24gl/",
        "independent_replication_certified": False,
        "files": [{"path": name, "bytes": len(data), "sha256": checksum(data)}
                  for name, data in sorted(entries.items())],
    }
    readme = (
        "Paper A pre-confirmatory scientific reproducibility snapshot\n\n"
        "The manuscript is DRAFT; H1/H2 have NOT been independently confirmed.\n"
        "This ZIP includes versioned source, protocol drafts, methodology, tests,\n"
        "lineage evidence and (if present) a technical audit report only.\n"
        "It does NOT include raw images, ground truth, H5, scores/F1 outcomes,\n"
        "or dataset/cache NPY payloads. Full Stage24GL numeric historical\n"
        "evidence is available separately in the same Git repository under\n"
        "results/paper_a_evidence/stage24gl/ (development/exploratory only).\n\n"
        "Extract next to a checkout of the recorded commit; use .venv.\n"
        "Run: python tests/test_paper_a_paired_f1_contract.py\n"
        "Run: python scripts/run_paper_a_prefreeze_one_shot.py\n"
        "Complete open scientific gates before calling any result confirmatory.\n"
    ).encode("utf-8")
    entries["REPRODUCIBILITY_README.txt"] = readme
    manifest["files"].append({"path": "REPRODUCIBILITY_README.txt",
                              "bytes": len(readme), "sha256": checksum(readme)})
    entries["REPRODUCIBILITY_MANIFEST.json"] = (
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    with zipfile.ZipFile(outzip, "x", compression=zipfile.ZIP_DEFLATED,
                         compresslevel=8, strict_timestamps=True) as archive:
        for name, data in sorted(entries.items()):
            zipinfo = zipfile.ZipInfo(name, date_time=ZIP_ENTRY_DATE)
            zipinfo.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(zipinfo, data)
    with zipfile.ZipFile(outzip, "r") as archive:
        if archive.testzip() is not None:
            raise RuntimeError("ZIP CRC failed")
        packed_manifest = json.loads(archive.read("REPRODUCIBILITY_MANIFEST.json"))
        for item in packed_manifest["files"]:
            if checksum(archive.read(item["path"])) != item["sha256"]:
                raise RuntimeError("ZIP SHA256 validation failed: " + item["path"])
    digest = checksum(outzip.read_bytes())
    sidecar = outzip.with_suffix(".sha256.txt")
    sidecar.write_text(digest + "  " + outzip.name + "\n", encoding="utf-8")
    return {
        "status": manifest["status"], "zip_path": str(outzip),
        "zip_sha256": digest, "zip_bytes": outzip.stat().st_size,
        "included_files": len(entries) - 1, "latest_overnight_audit_included": extra is not None,
        "manifest_inside_zip": True, "raw_or_GT_data_included": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outdir", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--audit-dir", type=Path, default=DEFAULT_AUDITS)
    args = parser.parse_args()
    info = build_bundle(args.outdir, args.audit_dir)
    print(json.dumps(info, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
