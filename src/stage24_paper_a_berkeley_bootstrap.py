from __future__ import annotations
"""Paired BSDS500 bootstrap from original per-image 99-threshold Berkeley counts.

Counts, not per-image ODS/AP, are resampled. ODS and AP are recomputed from
the pooled curve for every replicate; OIS pools each image's best-threshold
counts (Berkeley convention). A reference numerical check prevents invented
or incompatible benchmark results.
"""
from collections import defaultdict
import csv
import json
from pathlib import Path
import re
import numpy as np

COLUMNS=("threshold","cntR","sumR","cntP","sumP")


def _f1(p,r):
    return float((2.*p*r)/(p+r)) if p+r>0 else 0.


def _curve_metrics(rows):
    """Return ODS/OIS/AP from [image, threshold, five count fields] tensor."""
    x=np.asarray(rows,dtype=np.float64)
    if x.ndim!=3 or x.shape[1:]!=(99,5):
        raise ValueError("Expected [N,99,5] Berkeley count tensor")
    t=x[0,:,0]
    if not np.allclose(x[:,:,0],t[None,:],rtol=1e-7,atol=1e-7):
        raise ValueError("Unequal threshold grids among BSDS images")
    sums=np.sum(x[:,:,1:],axis=0)
    cr,sr,cp,sp=sums.T
    r=np.divide(cr,sr,out=np.zeros_like(cr),where=sr>0)
    p=np.divide(cp,sp,out=np.zeros_like(cp),where=sp>0)
    f=np.divide(2*r*p,r+p,out=np.zeros_like(r),where=(r+p)>0)
    # Berkeley's neighboring-point interpolation of the dataset PR curve.
    win=int(np.argmax(f))
    ods_sample=float(f[win])
    ods_best=ods_sample
    for j in range(98):
        w=np.linspace(0.,1.,101)
        ri=r[j]*(1-w)+r[j+1]*w
        pi=p[j]*(1-w)+p[j+1]*w
        fi=np.divide(2*ri*pi,ri+pi,out=np.zeros_like(ri),where=(ri+pi)>0)
        ods_best=max(ods_best,float(np.max(fi)))
    # One optimal threshold per image; aggregate counts BEFORE computing F1.
    candidates=x[:,:,1:]
    ri=np.divide(candidates[:,:,0],candidates[:,:,1],
                 out=np.zeros_like(candidates[:,:,0]),
                 where=candidates[:,:,1]>0)
    pi=np.divide(candidates[:,:,2],candidates[:,:,3],
                 out=np.zeros_like(candidates[:,:,2]),
                 where=candidates[:,:,3]>0)
    fi=np.divide(2*ri*pi,ri+pi,out=np.zeros_like(ri),where=(ri+pi)>0)
    opt=np.argmax(fi,axis=1)  # first maximum, like MATLAB
    total=np.sum(candidates[np.arange(len(x)),opt],axis=0)
    rc=total[0]/total[1] if total[1]>0 else 0.
    pc=total[2]/total[3] if total[3]>0 else 0.
    ois=_f1(pc,rc)
    # Berkeley uses a 101-point integral over unique recall locations.
    idx=np.argsort(r,kind="stable")
    rr,pp=r[idx],p[idx]
    uu,first=np.unique(rr,return_index=True)
    precision=pp[first]
    grid=np.linspace(0,1,101)
    if len(uu)>=2:
        pv=np.interp(grid,uu,precision,left=0.,right=0.)
        ap=float(np.sum(pv)*.01)
    else:
        ap=0.
    return {"ODS":ods_best,"ODS_sampled":ods_sample,
            "OIS":ois,"AP":ap,"ODS_threshold_sampled":float(t[win])}


def _read_rows(path):
    result=[]
    with Path(path).open(encoding="utf-8") as f:
        for line in f:
            if not line.strip():continue
            cols=line.split()
            if len(cols)!=5:
                raise RuntimeError("Invalid Berkeley ev1 source: "+str(path))
            result.append([float(v) for v in cols])
    arr=np.asarray(result,dtype=float)
    if arr.shape!=(99,5) or not np.isfinite(arr).all():
        raise RuntimeError("Invalid 99-threshold Berkeley counts: "+str(path))
    return arr


def load_official_counts(root):
    root=Path(root)
    methods={}
    for folder in sorted((root/"matlab").glob("*")):
        if not folder.is_dir() or not re.fullmatch(r"[A-Za-z0-9_.-]+",folder.name):
            continue
        files=sorted(folder.glob("*_ev1.txt"))
        if not files:continue
        images={p.name[:-8]:_read_rows(p) for p in files}
        if len(images)!=len(files):
            raise RuntimeError("Duplicate Berkeley image IDs for "+folder.name)
        methods[folder.name]=images
    return methods


def load_archived_counts(path):
    """Read CSV generated by Stage24 archive and compare without rerunning MATLAB."""
    output=defaultdict(lambda:defaultdict(list))
    with Path(path).open(encoding="utf-8",newline="") as f:
        rd=csv.DictReader(f)
        for row in rd:
            method,image=row["method"],row["image_id"]
            output[method][image].append([float(row[k]) for k in COLUMNS])
    return {k:{i:np.asarray(v) for i,v in images.items()}
            for k,images in output.items()}


def _stack(methods, name, ids):
    return np.stack([methods[name][iid] for iid in ids],axis=0)


def _check_reference(name, measurements, expected):
    """Block report if reimplementation does not reproduce official aggregate."""
    if not expected:return {"status":"reference_missing","metrics":measurements}
    diff={k:float(measurements[k]-float(expected[k]))
          for k in ("ODS","OIS","AP") if k in expected}
    # AP code may have subtle interpolation conventions; do not certify until
    # the numerical result matches the original MATLAB within a strict margin.
    if any(abs(v)>.003 for v in diff.values()):
        return {"status":"mismatch_DO_NOT_CITE","differences":diff,
                "recalculated":measurements}
    return {"status":"verified_against_official", "differences":diff,
            "recalculated":measurements}


def paired_bootstrap(methods, comparisons, official_summary=None, seed=20261104,
                     replicates=1000):
    if replicates<200:raise ValueError("At least 200 bootstrap replicates required")
    official=(official_summary or {}).get("methods",{})
    checks,rows,contrasts=[],[],[]
    for method,entries in methods.items():
        ids=sorted(entries)
        if len(ids)!=100:
            continue
        arr=_stack(methods,method,ids)
        measured=_curve_metrics(arr)
        checks.append({"method":method,**_check_reference(method,measured,official.get(method))})
    verified={r["method"] for r in checks
              if r["status"]=="verified_against_official"}
    rng=np.random.default_rng(seed)
    for a,b in comparisons:
        if a not in methods or b not in methods:
            continue
        if a not in verified or b not in verified:
            contrasts.append({"method":a,"reference":b,"status":"BLOCKED_REFERENCE_NOT_VERIFIED"})
            continue
        ids=sorted(set(methods[a]) & set(methods[b]))
        if len(ids)!=100 or set(ids)!=set(methods[a]) or set(ids)!=set(methods[b]):
            contrasts.append({"method":a,"reference":b,"status":"BLOCKED_UNMATCHED_IMAGES"})
            continue
        xa,xb=_stack(methods,a,ids),_stack(methods,b,ids)
        base_a=_curve_metrics(xa);base_b=_curve_metrics(xb)
        deltas={k:[] for k in ("ODS","OIS","AP")}
        for j in range(replicates):
            chosen=rng.integers(0,len(ids),len(ids))
            aa,bb=_curve_metrics(xa[chosen]),_curve_metrics(xb[chosen])
            for k in deltas:deltas[k].append(aa[k]-bb[k])
        for k,arr in deltas.items():
            values=np.asarray(arr,float)
            rows.append({"method":a,"reference":b,"metric":k,
                         "delta":float(base_a[k]-base_b[k]),
                         "ci95_low":float(np.quantile(values,.025)),
                         "ci95_high":float(np.quantile(values,.975)),
                         "p_bootstrap_two_sided":float(min(1.,2*min(np.mean(values>=0),np.mean(values<=0)))),
                         "replicates":replicates,"n_unique_images":100,
                         "methodology":"paired bootstrap image-level count reaggregation",
                         "reference_status":"verified_against_official"})
        contrasts.append({"method":a,"reference":b,"status":"complete"})
    return {"verification":checks,"comparisons":contrasts,"confidence_intervals":rows,
            "caution":"ODS/OIS are oracle threshold summaries of re-sampled validation, not fixed-threshold prospective test results"}


def write_results(out, data):
    out=Path(out);out.mkdir(parents=True,exist_ok=True)
    (out/"bootstrap_integrity.json").write_text(json.dumps({
        k:v for k,v in data.items() if k!="confidence_intervals"},
        indent=2),encoding="utf-8")
    csv_path=out/"bootstrap_paired_ods_ois_ap.csv"
    rows=data["confidence_intervals"]
    if rows:
        with csv_path.open("w",newline="",encoding="utf-8") as f:
            writer=csv.DictWriter(f,fieldnames=list(rows[0]))
            writer.writeheader();writer.writerows(rows)
    elif csv_path.exists():
        csv_path.unlink()
    return csv_path


def synthetic_contract():
    """Bootstrap numeric pipeline and shape check, no false reference certification."""
    rng=np.random.default_rng(42)
    rows=np.zeros((4,99,5),float)
    rows[:,:,0]=np.arange(1,100)[None,:]/100.
    rows[:,:,2]=100.
    rows[:,:,4]=100.
    rows[:,:,1]=rng.integers(15,55,size=(4,99))
    rows[:,:,3]=rng.integers(10,65,size=(4,99))
    met=_curve_metrics(rows)
    return all(np.isfinite(met[k]) and 0<=met[k]<=1.01 for k in ("ODS","OIS","AP"))
